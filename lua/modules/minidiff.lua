-- Изменения относительно git-индекса: знаки в колонке слева, ,h — показать
-- сам дифф прямо в тексте. Весь плагин — один файл, git запускается через
-- vim.loop.spawn списком аргументов, без шелла.
require("mini.diff").setup({
  view = {
    -- Явно "sign": дефолт зависит от 'number', а он включён (set.lua), и тогда
    -- плагин красил бы сами номера строк вместо колонки знаков.
    style = "sign",
    -- Обычный юникод: Nerd Font в терминале нет.
    signs = { add = "+", change = "~", delete = "_" },
  },
})

-- Оверлей: старые строки показываются виртуальными строками поверх буфера,
-- удалённый блок разворачивается на месте. Повторное нажатие убирает.
vim.keymap.set("n", ",h", MiniDiff.toggle_overlay, { noremap = true, silent = true })

